package com.nobodiiiii.createbiotech.content.slimemimic;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.WeakHashMap;

import com.nobodiiiii.createbiotech.CreateBiotech;
import com.nobodiiiii.createbiotech.content.slimebelt.SlimeBeltAcquisitionHandler;
import com.nobodiiiii.createbiotech.entity.SlimeBionicEntity;

import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.Container;
import net.minecraft.world.entity.EquipmentSlot;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.Saddleable;
import net.minecraft.world.entity.animal.horse.AbstractChestedHorse;
import net.minecraft.world.entity.animal.horse.AbstractHorse;
import net.minecraft.world.entity.item.ItemEntity;
import net.minecraft.world.entity.monster.EnderMan;
import net.minecraft.world.entity.monster.Slime;
import net.minecraft.world.entity.npc.InventoryCarrier;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.Items;
import net.neoforged.bus.api.EventPriority;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.EventBusSubscriber;
import net.neoforged.neoforge.event.entity.living.LivingDeathEvent;
import net.neoforged.neoforge.event.entity.living.LivingDropsEvent;

/** Keeps actual possessions separate from loot generated by the imitated creature. */
@EventBusSubscriber(modid = CreateBiotech.MOD_ID)
public final class SlimeMimicCarriedDrops {
	// A canceled death must not take any items. Weak keys also release snapshots when no drops event follows.
	private static final Map<LivingEntity, List<ItemStack>> PENDING = new WeakHashMap<>();

	private SlimeMimicCarriedDrops() {}

	@SubscribeEvent(priority = EventPriority.LOWEST)
	public static void onLivingDeath(LivingDeathEvent event) {
		LivingEntity entity = event.getEntity();
		if (entity.level() instanceof ServerLevel
			&& (SlimeMimicHandler.isSlimeMimic(entity) || entity instanceof SlimeBionicEntity))
			PENDING.put(entity, copyCarriedItems(entity));
	}

	static void replaceDrops(LivingDropsEvent event) {
		LivingEntity entity = event.getEntity();
		List<ItemStack> items = PENDING.remove(entity);
		if (items == null)
			items = copyCarriedItems(entity);
		clearCarriedItems(entity);
		event.getDrops().clear();
		for (ItemStack stack : items) {
			ItemEntity drop = new ItemEntity(entity.level(), entity.getX(), entity.getY(), entity.getZ(), stack);
			drop.setDefaultPickUpDelay();
			event.getDrops().add(drop);
		}
	}

	/** Self-destruction bypasses LivingDeathEvent and the normal death-loot pipeline. */
	public static void dropCarriedItems(LivingEntity entity) {
		if (!(entity.level() instanceof ServerLevel))
			return;
		removeCarriedItems(entity).forEach(entity::spawnAtLocation);
	}

	/** Take the same possessions for death, self-destruction or successful surgical placement. */
	public static List<ItemStack> removeCarriedItems(LivingEntity entity) {
		List<ItemStack> items = copyCarriedItems(entity);
		clearCarriedItems(entity);
		return items;
	}

	private static List<ItemStack> copyCarriedItems(LivingEntity entity) {
		List<ItemStack> items = new ArrayList<>();
		// Snapshot before Mob applies drop chances, vanishing and random durability loss.
		for (EquipmentSlot slot : EquipmentSlot.values())
			copyItem(items, entity.getItemBySlot(slot));
		if (entity instanceof InventoryCarrier carrier)
			copyContainer(items, carrier.getInventory());
		else if (entity instanceof Container container)
			copyContainer(items, container);

		if (entity instanceof SlimeBionicEntity bionic) {
			items.addAll(bionic.getBionicEquipment().copyMountEquipment());
		} else if (entity instanceof AbstractHorse horse) {
			copyItem(items, horse.getSlot(AbstractHorse.EQUIPMENT_SLOT_OFFSET).get());
			for (int slot = 0; slot < horse.getInventorySize() - 1; slot++)
				copyItem(items, horse.getSlot(AbstractHorse.INVENTORY_SLOT_OFFSET + slot).get());
			if (horse instanceof AbstractChestedHorse chested && chested.hasChest())
				items.add(new ItemStack(Items.CHEST));
		} else if (entity instanceof Saddleable saddleable && saddleable.isSaddled()) {
			ItemStack saddle = entity.getSlot(AbstractHorse.EQUIPMENT_SLOT_OFFSET).get();
			copyItem(items, saddle.isEmpty() ? new ItemStack(Items.SADDLE) : saddle);
		}
		if (entity instanceof EnderMan enderman && enderman.getCarriedBlock() != null)
			copyItem(items, new ItemStack(enderman.getCarriedBlock().getBlock()));
		if (entity instanceof Slime slime)
			copyItem(items, SlimeBeltAcquisitionHandler.copyCarriedBelt(slime));
		return items;
	}

	private static void copyContainer(List<ItemStack> items, Container container) {
		for (int slot = 0; slot < container.getContainerSize(); slot++)
			copyItem(items, container.getItem(slot));
	}

	private static void copyItem(List<ItemStack> items, ItemStack stack) {
		if (!stack.isEmpty())
			items.add(stack.copy());
	}

	private static void clearCarriedItems(LivingEntity entity) {
		for (EquipmentSlot slot : EquipmentSlot.values())
			entity.setItemSlot(slot, ItemStack.EMPTY);
		if (entity instanceof InventoryCarrier carrier)
			carrier.getInventory().clearContent();
		else if (entity instanceof Container container)
			container.clearContent();

		if (entity instanceof SlimeBionicEntity bionic) {
			bionic.getBionicEquipment().removeMountEquipment();
		} else if (entity instanceof AbstractHorse horse) {
			horse.getSlot(AbstractHorse.EQUIPMENT_SLOT_OFFSET).set(ItemStack.EMPTY);
			for (int slot = 0; slot < horse.getInventorySize() - 1; slot++)
				horse.getSlot(AbstractHorse.INVENTORY_SLOT_OFFSET + slot).set(ItemStack.EMPTY);
			if (horse instanceof AbstractChestedHorse chested)
				chested.setChest(false);
		}
		if (entity instanceof EnderMan enderman)
			enderman.setCarriedBlock(null);
	}
}
